function readLocale(): Locale {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw === "ko" || raw === "en" || raw === "es" || raw === "zh") return raw;
  } catch {
    /* ignore */
  }
  const nav = navigator.language.toLowerCase();
  if (nav.startsWith("ko")) return "ko";
  if (nav.startsWith("es")) return "es";
  if (nav.startsWith("zh")) return "zh";
  if (nav.startsWith("en")) return "en";
  return "ko";
}

let activeLocale: Locale = readLocale();

export type TFn = (key: MsgKey, vars?: Record<string, string | number>) => string;

export function formatMessage(locale: Locale, key: MsgKey, vars?: Record<string, string | number>): string {
  let s = catalogs[locale][key] ?? catalogs.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** For non-React callers (ingest, db, time). */
export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  return formatMessage(activeLocale, key, vars);
}

function applyHtmlLang(locale: Locale) {
  const html = LOCALES.find((l) => l.id === locale)?.html ?? "ko";
  document.documentElement.lang = html;
}

applyHtmlLang(activeLocale);

interface LocaleCtx {
  locale: Locale;
  setLocale: (next: Locale) => void;
  t: TFn;
}

const LocaleContext = createContext<LocaleCtx | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(activeLocale);
  const value = useMemo<LocaleCtx>(() => {
    const setLocale = (next: Locale) => {
      activeLocale = next;
      try {
        localStorage.setItem(STORAGE_KEY, next);
      } catch {
        /* ignore */
      }
      applyHtmlLang(next);
      setLocaleState(next);
    };
    return {
      locale,
      setLocale,
      t: (key, vars) => formatMessage(locale, key, vars),
    };
  }, [locale]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useI18n(): LocaleCtx {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error("useI18n must be used within LocaleProvider");
  return ctx;
}
